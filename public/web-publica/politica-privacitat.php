    <li>Dret de rectificació de les dades incorrectes o incompletes.</li>
    <li>Dret de supressió de les seves dades.</li>
    <li>Dret a retirar el consentiment.</li>
    <li>Dret a sol·licitar la limitació del tractament.</li>
