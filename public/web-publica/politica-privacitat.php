<h2>11. Cookies de tercers</h2>

<p>
    Aquest lloc web no utilitza serveis de tercers destinats a fer el
    seguiment dels visitants, elaborar perfils de navegació o mostrar
    publicitat personalitzada.
</p>

<p>
    Per tant, no s'utilitzen cookies de tercers amb finalitats d'analítica,
    publicitat o seguiment.
</p>

