<p>
    El responsable d'aquest lloc web és <strong>Elliot Fernandez</strong>.
</p>

<p>
    Per a qualsevol qüestió relacionada amb la privacitat o el tractament
    de dades personals, podeu contactar a través de:
</p>

<ul>
    <li>
        Correu electrònic:
        <a href="mailto:web(@)hispantic.com">web@hispantic.com</a>
    </li>
</ul>

<h2>2. Principis de privacitat</h2>

<p>
    Aquest lloc web aplica un criteri de minimització de dades. Només es
    recullen i es conserven les dades personals estrictament necessàries
    per permetre el registre dels usuaris, la participació en el sistema
    de comentaris i la comunicació mitjançant el formulari de contacte.
</p>

<p>
    <strong>No utilitzem les dades personals dels usuaris amb finalitats
        publicitàries, comercials o de perfilat.</strong>
</p>

<p>
    Tampoc venem, cedim ni compartim les dades personals dels usuaris amb
    tercers amb finalitats comercials.
</p>

<h2>3. Dades personals que es poden recollir</h2>

<p>
    En funció de la funcionalitat utilitzada, el lloc web pot recollir
    únicament les dades necessàries per identificar l'usuari:
</p>

<ul>
    <li>Nom d'usuari.</li>
    <li>Adreça de correu electrònic.</li>
    <li>Nom.</li>
    <li>Cognoms.</li>
</ul>

<p>
    No es demanaran dades personals addicionals que no siguin necessàries
    per al funcionament dels serveis disponibles al lloc web.
</p>

<h2>4. Registre d'usuaris</h2>

<p>
    Per poder disposar d'un compte d'usuari és necessari facilitar les dades
    imprescindibles per identificar-lo: nom d'usuari, adreça de correu
    electrònic, nom i cognoms.
</p>

<p>
    Abans de completar el registre, l'usuari haurà d'acceptar expressament
    el tractament de les seves dades personals d'acord amb aquesta política
    de privacitat.
</p>

<p>
    Les dades del compte s'utilitzen exclusivament per gestionar el compte
    de l'usuari i permetre-li accedir a les funcionalitats reservades als
    usuaris registrats, com ara la participació en el sistema de comentaris.
</p>

<h2>5. Sistema de comentaris</h2>

<p>
    Els usuaris registrats poden participar en el sistema de comentaris
    del lloc web.
</p>

<p>
    Per poder publicar comentaris és necessari disposar d'un compte d'usuari.
    La identificació de l'autor del comentari es realitza mitjançant el
    compte d'usuari corresponent.
</p>

<p>
    Les dades personals no s'utilitzen per fer seguiment de l'activitat
    de l'usuari fora de les funcionalitats pròpies del lloc web.
</p>

<h2>6. Formulari de contacte</h2>

<p>
    El lloc web disposa d'un formulari de contacte que permet als visitants
    posar-se en contacte amb el responsable del lloc web.
</p>

<p>
    Les dades facilitades mitjançant aquest formulari s'utilitzen únicament
    per respondre la consulta o petició realitzada per la persona usuària.
</p>

<p>
    Aquestes dades no s'utilitzen per enviar comunicacions comercials ni
    per elaborar perfils dels usuaris.
</p>

<h2>7. Consentiment per al tractament de les dades</h2>

<p>
    El tractament de les dades personals dels usuaris es realitza amb el
    seu <strong>consentiment exprés</strong>, que es demana abans de completar
    el registre o quan sigui necessari per a la funcionalitat corresponent.
</p>

<p>
    L'usuari pot retirar el seu consentiment en qualsevol moment. La retirada
    del consentiment no afecta la licitud del tractament realitzat abans
    de la seva retirada.
</p>

<h2>8. Conservació de les dades</h2>

<p>
    Les dades personals es conservaran mentre l'usuari mantingui el seu
    compte actiu i siguin necessàries per prestar les funcionalitats
    sol·licitades.
</p>

<p>
    Quan l'usuari sol·liciti la baixa i l'eliminació del seu compte, les
    seves dades personals seran eliminades, excepte quan existeixi una
    obligació legal que exigeixi conservar-les durant un període determinat.
</p>

<h2>9. Baixa i eliminació de les dades personals</h2>

<p>
    Qualsevol usuari registrat pot sol·licitar la baixa del seu compte i
    l'<strong>eliminació de les seves dades personals</strong>.
</p>

<p>
    La sol·licitud es pot realitzar mitjançant les funcionalitats disponibles
    dins del compte d'usuari o, si aquesta opció no està disponible,
    contactant amb el responsable del lloc web a través de:
</p>

<p>
    <a href="mailto:web(@)hispantic.com">web@hispantic.com</a>
</p>

<p>
    Un cop rebuda i verificada la sol·licitud, les dades personals seran
    eliminades d'acord amb la normativa aplicable.
</p>

<h2>10. Cookies</h2>

<p>
    Aquest lloc web no utilitza cookies d'analítica, publicitat, seguiment
    ni perfilat.
</p>

<p>
    <strong>No utilitzem Google Analytics ni cap altre sistema d'analítica
        de visites.</strong>
</p>

<p>
    Els visitants que naveguen pel lloc web sense iniciar sessió no tenen
    cap cookie pròpia associada al lloc web.
</p>

<h3>Cookie tècnica per als usuaris registrats</h3>

<p>
    Quan un usuari inicia sessió, el lloc web utilitza una única cookie
    tècnica denominada <code>token</code>.
</p>

<p>
    Aquesta cookie és estrictament necessària per al funcionament de
    l'autenticació i té com a finalitat identificar tècnicament l'usuari
    registrat i mantenir la seva sessió.
</p>

<p>
    La cookie <code>token</code> no s'utilitza per fer seguiment de la
    navegació, elaborar perfils, analitzar el comportament de l'usuari
    amb finalitats comercials ni mostrar publicitat.
</p>

