<h1>Compromís de responsabilitat i qualitat dels continguts amb els lectors</h1>

<p>La política editorial de la pàgina web <strong>«Elliot.cat» i la secció "Història Oberta"</strong> es basa en 7 punts que garanteixen que tots els <strong>nostres continguts siguin rigorosos, honestos, fiables i transparents.</strong></p>

<ul>
    <li>
        Volem que sigui fàcil saber <strong>qui escriu en aquest lloc web</strong> i
        quins coneixements té per fer-ho.
    </li>

    <li>
        Volem que coneguis les nostres fonts, <strong>en qui ens inspirem i els
            mitjans i les eines que utilitzem.</strong>
    </li>

    <li>
        Treballem perquè tot això sigui possible oferint als lectors
        <strong>la possibilitat d'informar-nos de qualsevol error</strong> que
        detectin i de proposar-nos qualsevol millora.
    </li>

</ul>

<p>Basem la nostra <strong>ètica editorial en 7 punts</strong>, que desenvolupem a continuació:</p>

<h2>1. Veracitat de la informació</h2>

<p>
    Tota la informació històrica que publiquem és revisada per garantir que sigui
    certa. Per complir aquest objectiu, procurem documentar-nos a partir de fonts
    primàries i incloem en tots els articles una llista de la bibliografia bàsica
    consultada.
</p>

<h2>2. Autors especialitzats</h2>

<p>
    Cada autor dels articles coneix perfectament el tema sobre el qual treballa.
    Comptem amb especialistes en cada àmbit: persones que demostren diàriament
    posseir un ampli coneixement sobre la matèria en què escriuen.
    Perquè els puguis conèixer, oferim informació sobre cadascun d'ells, així com
    enllaços als seus perfils a les xarxes socials i a la seva biografia.
</p>

<h2>3. Continguts originals</h2>

<p>
    Tots els continguts que publiquem són originals. No copiem ni traduïm altres
    llocs web. En cas d'haver utilitzat altres fonts, hi enllacem les referències
    corresponents i citem els autors o propietaris de les imatges, els mitjans i
    els recursos que utilitzem, amb l'objectiu d'oferir la informació més precisa
    possible i reconèixer-ne l'autoria.
</p>

<h2>4. No fem servir clickbait</h2>

<p>
    No utilitzem titulars falsos o sensacionalistes per atreure el lector sense
    que el contingut promès es trobi realment a l'article. Som rigorosos i
    veraços, i per això els títols dels nostres articles corresponen al contingut
    que hi trobaràs.
</p>

<p>
    A més, no generem expectatives sobre continguts que no apareguin en el cos
    de l'article.
</p>

<h2>5. Qualitat i excel·lència dels continguts</h2>

<p>
    Creem articles i continguts de qualitat i treballem contínuament per assolir
    l'excel·lència. Procurem tenir cura de tots els detalls i oferir al lector
    la informació que busca i necessita.
</p>

<h2>6. Correcció d'errors</h2>

<p>
    Sempre que detectem un error, o quan algú ens el comunica, el revisem i el
    corregim. Disposem d'un sistema intern de control d'errors que ens ajuda a
    millorar constantment els nostres articles i a evitar que aquests errors es
    repeteixin en el futur.
</p>

<h2>7. Millora contínua</h2>

<p>
    Millorem regularment el contingut dels nostres articles. D'una banda,
    corregint errors i, de l'altra, ampliant-ne el contingut.
</p>

<p>
    Gràcies a aquesta pràctica, tots els continguts del web es transformen en
    continguts de referència útils per a tots els lectors, independentment del
    moment en què els consultin.
</p>

